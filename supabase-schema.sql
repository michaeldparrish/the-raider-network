-- The Raider Network - planned Supabase schema (v3 Loot Hunts)
-- Keep DEMO_MODE=true until local design review is complete.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null check (char_length(display_name) between 2 and 30),
  platform text not null default 'Cross-platform',
  region text not null default 'NA East',
  created_at timestamptz not null default now()
);
create table if not exists public.private_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  raider_tag text not null check (char_length(raider_tag) between 2 and 50)
);
create table if not exists public.loot_hunts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  item text not null check (char_length(item) between 1 and 100),
  map text not null,
  region text not null,
  platform text not null,
  squad_size int not null default 3 check (squad_size between 2 and 3),
  current_members int not null default 1 check (current_members between 1 and 3),
  desired_time text default '' check (char_length(desired_time) <= 80),
  details text default '' check (char_length(details) <= 500),
  status text not null default 'open' check (status in ('open','full','completed')),
  created_at timestamptz not null default now()
);
create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 1000),
  created_at timestamptz not null default now(),
  check (sender_id <> recipient_id)
);
alter table public.profiles enable row level security;
alter table public.private_profiles enable row level security;
alter table public.loot_hunts enable row level security;
alter table public.messages enable row level security;
create policy "profiles readable by everyone" on public.profiles for select using (true);
create policy "users insert own profile" on public.profiles for insert to authenticated with check (auth.uid() = id);
create policy "users update own profile" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);
create policy "private profile owner reads" on public.private_profiles for select to authenticated using (auth.uid() = id);
create policy "private profile owner inserts" on public.private_profiles for insert to authenticated with check (auth.uid() = id);
create policy "private profile owner updates" on public.private_profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);
create policy "hunts readable by everyone" on public.loot_hunts for select using (true);
create policy "users create own hunts" on public.loot_hunts for insert to authenticated with check (auth.uid() = user_id);
create policy "users update own hunts" on public.loot_hunts for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "users delete own hunts" on public.loot_hunts for delete to authenticated using (auth.uid() = user_id);
create policy "message participants read" on public.messages for select to authenticated using (auth.uid() = sender_id or auth.uid() = recipient_id);
create policy "users send own messages" on public.messages for insert to authenticated with check (auth.uid() = sender_id);
create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id,display_name,platform,region) values (new.id,coalesce(new.raw_user_meta_data->>'display_name','Raider'),coalesce(new.raw_user_meta_data->>'platform','Cross-platform'),coalesce(new.raw_user_meta_data->>'region','NA East')) on conflict (id) do nothing;
  insert into public.private_profiles (id,raider_tag) values (new.id,coalesce(new.raw_user_meta_data->>'raider_tag','Pending')) on conflict (id) do nothing;
  return new;
end;$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

