-- Community stats for the homepage (replaces demo values in data/demo-users.json)
create or replace view public.community_stats as
select (select count(*) from public.profiles) as active_raiders,
       (select count(*) from public.trade_requests where status = 'closed') as trades_completed,
       (select count(*) from public.loot_hunts where status = 'open') as open_hunts;

